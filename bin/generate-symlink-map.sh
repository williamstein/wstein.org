#!/usr/bin/env bash
set -euo pipefail

python3 - <<'PY'
import json
import os

root = "/home/user/www"
out = "/home/user/wstein-r2-worker/src/symlink-map.js"
aliases = {}
broken = []
outside = []

for dirpath, dirnames, filenames in os.walk(root, followlinks=False):
    for name in list(dirnames) + list(filenames):
        path = os.path.join(dirpath, name)
        if not os.path.islink(path):
            continue

        rel = os.path.relpath(path, root).replace(os.sep, "/")
        real = os.path.realpath(path)

        if not os.path.exists(real):
            broken.append(rel)
            continue

        if os.path.commonpath([root, real]) != root:
            outside.append(rel)
            continue

        target = os.path.relpath(real, root).replace(os.sep, "/")
        if os.path.isdir(real):
            aliases[rel] = target
            aliases[f"{rel}/"] = f"{target}/"
        else:
            aliases[rel] = target

items = sorted(aliases.items(), key=lambda item: (-len(item[0]), item[0]))

with open(out, "w", encoding="utf-8") as f:
    f.write("// Generated by bin/generate-symlink-map.sh. Do not edit by hand.\n")
    f.write(f"// Internal symlink aliases: {len(items)}; broken skipped: {len(broken)}; outside skipped: {len(outside)}.\n")
    f.write("export const SYMLINK_ALIASES = ")
    json.dump(items, f, separators=(",", ":"))
    f.write(";\n")

print(f"wrote {out}")
print(f"internal aliases: {len(items)}")
print(f"broken symlinks skipped: {len(broken)}")
print(f"outside symlinks skipped: {len(outside)}")
PY
